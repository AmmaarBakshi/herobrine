"""Writes docs/VOICE_SCRIPT.md, the recording script, from the dialogue data.

Run from the repo root:  python tools/gen_voice_script.py
Standard library only. Re-run it after editing dialogue.json or adding recordings: each line is
marked as recorded once its .ogg exists under src/main/resources/assets/.
"""
import json
from pathlib import Path

DIALOGUE = Path("src/main/resources/data/herobrine/dialogue/dialogue.json")
TRIGGERS = Path("src/main/resources/data/herobrine/dialogue/triggers.json")
ASSETS = Path("src/main/resources/assets")
OUT = Path("docs/VOICE_SCRIPT.md")

CATEGORY_TITLES = {
    "random": "Encounters (he has just been seen)",
    "reaction": "Reactions (how the appearance ended)",
    "idle": "Out of nowhere (voice only)",
    "progression": "Equipment progression",
    "wither": "The Wither",
    "ender_dragon": "The Ender Dragon",
    "warden": "The Warden",
    "weather": "Weather",
    "caves": "Caves",
    "building": "Building",
    "death": "Death and respawn",
    "achievements": "Milestones",
    "fourth_wall": "Fourth wall (extremely rare)",
    "rare": "Rare philosophy",
}


def audio_file(line, category):
    audio = line.get("audio")
    if not audio:
        name = line["id"][len(category) + 1:] if line["id"].startswith(category + ".") else line["id"]
        audio = "herobrine:voice/" + category + "/" + name.replace(".", "_")
    namespace, _, path = audio.partition(":") if ":" in audio else ("herobrine", "", audio)
    return Path("assets") / namespace / "sounds" / (path + ".ogg")


def when_text(line):
    parts = []
    when = line.get("when", {})
    for tag in when.get("tags", []):
        parts.append(f"`{tag}`")
    for tag in when.get("not_tags", []):
        parts.append(f"not `{tag}`")
    for counter, value in when.get("memory", {}).items():
        parts.append(f"{counter} {value}")
    if line.get("once"):
        parts.append("once ever")
    if line.get("priority"):
        parts.append(f"priority {line['priority']}")
    return ", ".join(parts) if parts else "any time"


def escape(text):
    return text.replace("|", "\\|")


def main():
    lines = json.loads(DIALOGUE.read_text(encoding="utf-8"))["lines"]
    triggers = json.loads(TRIGGERS.read_text(encoding="utf-8"))
    by_category = {}
    for line in lines:
        category = line.get("category") or line["id"].split(".")[0]
        by_category.setdefault(category, []).append(line)

    recorded = 0
    sections = []
    for category, entries in by_category.items():
        rows = []
        for i, line in enumerate(entries, 1):
            file = audio_file(line, category)
            done = (Path("src/main/resources") / file).exists()
            recorded += done
            rows.append(f"| {'✅' if done else '⬜'} | `{file.name}` | {escape(line['text'])} | {escape(line.get('note', ''))} | {when_text(line)} |")
        folder = f"src/main/resources/assets/herobrine/sounds/voice/{category}/"
        title = CATEGORY_TITLES.get(category, category)
        sections.append(f"### {title}\n\nFolder: `{folder}`\n\n| | File | Line | Delivery | When |\n|---|---|---|---|---|\n" + "\n".join(rows))

    trigger_rows = []
    for name, rule in triggers.get("triggers", {}).items():
        trigger_rows.append(f"| `{name}` | {', '.join(rule.get('categories', [name]))} | {rule.get('chance', 1.0):g} | {rule.get('cooldown', 0)} s |")

    text = f"""# Herobrine: voice recording script

<!-- Generated by tools/gen_voice_script.py from data/herobrine/dialogue/dialogue.json. Edit those, then re-run. -->

**{recorded} of {len(lines)} lines recorded.** Until a line has a recording, the game shows its words as a
caption instead, so you can record in any order and test as you go.

## The voice

Herobrine is calm. Think of an artificial mind that has read everything and is mildly amused by all of
it: low, unhurried, precise diction, every consonant placed. He never shouts and never hurries; menace
comes from how relaxed he is. Let pauses breathe, especially before the last few words of a line. He is
sarcastic but rarely cruel, fond of the player in a possessive way, and a little hurt when ignored.

- Speak close to the microphone, at a conversational level. Quiet lines (caves, the Warden) can be
  almost a whisper.
- No effects: no reverb, pitch shifting or distortion. The game plays the voice as is, "inside the
  player's head".
- Leave about 0.2 s of silence before and after each take, and trim the rest.

## Recording format

- **Mono** Ogg Vorbis (`.ogg`), 44.1 or 48 kHz. Stereo files are played too, but mono is half the size.
- One file per line, named exactly as in the tables below, in that category's folder.
- Normalise takes to a similar loudness (about -16 LUFS works well).

Converting a take with ffmpeg:

```sh
ffmpeg -i take.wav -ac 1 -ar 44100 -c:a libvorbis -q:a 5 first.ogg
```

Recordings can also ship in a resource pack (`assets/herobrine/sounds/voice/...`), which overrides the mod's.

## Testing a recording in game

```
/herobrine voice say @s random.first        play one line (tab-completes every id)
/herobrine voice trigger @s progression tier:iron   let him choose, as if it happened
/herobrine voice recordings                  how many lines have a file, per category
```

Then run `python tools/gen_voice_script.py` to tick off what is done in this file.

## When he speaks

He says nothing most of the time. Each moment has a chance and a cooldown, there are at least
90 seconds between any two lines (`voiceMinGapSeconds`), and he never repeats one of his last eight
lines. Chances and cooldowns come from `triggers.json`:

| Moment | Categories, rarest first | Chance | Cooldown |
|---|---|---|---|
{chr(10).join(trigger_rows)}

## The script

{chr(10).join(chr(10) + s for s in sections)}
"""
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text.replace("\n\n\n", "\n\n"), encoding="utf-8")
    print(f"wrote {OUT}: {recorded}/{len(lines)} recorded")


if __name__ == "__main__":
    main()
